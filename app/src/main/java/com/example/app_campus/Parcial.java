package com.example.app_campus;

public class Parcial {

    public String materia;
    public String fecha;
    public String detalle;
    public String color;

    public Parcial(String materia, String fecha, String detalle, String color) {
        this.materia = materia;
        this.fecha = fecha;
        this.detalle = detalle;
        this.color = color;
    }
}
